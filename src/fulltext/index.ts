// The 30 full-text works no longer live in the gateway bundle at all (fleet
// #2191, following the pattern #2189 used for medical-codes' ICD-10-PCS
// table). They used to be `await import()`ed here (fleet #1408) to keep
// object construction off the cold-start path — but esbuild does not
// code-split a Worker into separate chunks, so a dynamic `import('./x.json')`
// still inlines the same bytes into the single bundled script. Measured on
// the real gateway bundle post-#2189: this pack alone was 13.99MB, 33.9% of
// the whole thing, for tools most callers never touch.
//
// Each work's full JSON (identical to what used to sit at
// ./<work-slug>.json) now lives in the gateway's IDENTITY_KV namespace under
// its own key (`static-json:quotes-fulltext:<authorId>:<workSlug>`), uploaded
// by scripts/sync-gateway-static-json.mjs and read back lazily by
// workers/gateway/src/pack-static-blobs.ts — ONLY for the one work a call
// actually names, ONLY on the three tools that need full text (get_scene,
// get_act, get_chapter). A random_quote/search_quotes/list_authors call never
// touches any of this.
//
// list_full_text_works is the one function here that does NOT need a KV
// fetch: its output is a SUMMARY (title/year/act-or-chapter counts), which is
// tiny and known at build time — see ./works-meta.json (generated by
// scripts/build-quotes-worksmeta.mjs), the same "keep the small scalar
// fields, move only the big blob" split #2189 made for medical-codes'
// icd10pcs-meta.json.
//
// The per-tool caller (mcps/quotes/src/index.ts) reads the gateway-injected
// raw JSON string off `args._quotesFullTextWork` and passes it into the
// functions below. A KV outage/timeout/missing-key resolves to `''`
// (pack-static-blobs.ts's fail-soft posture) which these functions turn into
// "not found" rather than throwing — the same trade #2189 made.
//
// The `raw` (`args._quotesFullTextWork`) accepted below is always for the ONE
// work the caller named (authorId/workSlug already used by the gateway to
// pick the KV key) — these functions do not themselves search across works.

import worksMeta from './works-meta.json';
import type { FullAct, FullChapter, FullScene, FullTextWork } from './types';

export interface FullTextWorkSummary {
  workId: string;
  authorId: string;
  workSlug: string;
  workTitle: string;
  year: number;
  source: string;
  kind: 'play' | 'chapters';
  actCount?: number;
  sceneCount?: number;
  chapterCount?: number;
}

/** Synchronous — backed by the small static works-meta.json, never KV. */
export function listFullTextWorks(): FullTextWorkSummary[] {
  return worksMeta as FullTextWorkSummary[];
}

// Parsing a work's JSON is cheap (largest is ~1.1MB) but a call can name the
// same work repeatedly within one isolate's life (e.g. several get_scene
// calls against the same play), so the parsed object is memoized keyed by
// the raw string's IDENTITY (`===`), mirroring pcsTable(codes) in
// mcps/medical-codes/src/index.ts. The gateway's own loadQuotesFullTextWork()
// already memoizes the KV read per (authorId, workSlug) per isolate, so the
// SAME string reference arrives on every repeat call for that work — this
// just avoids re-parsing it.
let parsedWork: FullTextWork | null = null;
let parsedWorkSource: string | null = null;

function parseWork(raw: string): FullTextWork | undefined {
  if (!raw) return undefined;
  if (parsedWorkSource !== raw) {
    try {
      parsedWork = JSON.parse(raw) as FullTextWork;
    } catch (e) {
      console.error('quotes/fulltext: failed to parse injected work JSON:', e);
      parsedWork = null;
    }
    parsedWorkSource = raw;
  }
  return parsedWork ?? undefined;
}

/**
 * `raw` is the gateway-injected full JSON for the one work named by
 * authorId/workSlug (`args._quotesFullTextWork`) — this does NOT search
 * across works, it just decodes and sanity-checks the one blob handed to it.
 */
export function getFullWorkByAuthorSlug(raw: string, authorId: string, workSlug: string): FullTextWork | undefined {
  const work = parseWork(raw);
  if (!work || work.authorId !== authorId || work.workSlug !== workSlug) return undefined;
  return work;
}

export function getAct(raw: string, authorId: string, workSlug: string, act: number): FullAct | undefined {
  return getFullWorkByAuthorSlug(raw, authorId, workSlug)?.acts?.find((a) => a.number === act);
}

export function getScene(raw: string, authorId: string, workSlug: string, act: number, scene: number): FullScene | undefined {
  return getAct(raw, authorId, workSlug, act)?.scenes.find((s) => s.number === scene);
}

export function getChapter(raw: string, authorId: string, workSlug: string, chapter: number): FullChapter | undefined {
  return getFullWorkByAuthorSlug(raw, authorId, workSlug)?.chapters?.find((c) => c.number === chapter);
}

export type { FullAct, FullChapter, FullScene, FullSpeech, FullTextWork } from './types';
